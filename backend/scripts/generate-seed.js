// ---------- audio analysis: two versions per song ----------
function features(s, noise) {
  const [e, v, d, ac, ins, sp, tempo] = s.a.f;
  const j = (x, spread) => r3(clamp(x + between(-spread, spread)));
  const instrumental = s.lang === null;
  return {
    energy: j(e, noise), valence: j(v, noise), danceability: j(d, noise), acousticness: j(ac, noise),
    instrumentalness: instrumental ? j(Math.max(ins, 0.82), noise / 2) : j(Math.min(ins, 0.18), noise / 3),
    speechiness: j(sp, 0.02), loudness: Math.round((s.a.loud + between(-2, 2)) * 100) / 100,
    tempo: Math.round(clamp(tempo + between(-9, 9), 40, 220) * 10) / 10,
    key: int(0, 11), mode: rand() < s.a.major ? 1 : 0,
  };
}
