const segValues = [];
songs.forEach((s) => {
  const shape = pick(SHAPES);
  let t = 0;
  shape.forEach(([, share, de, dv], k) => {
    const end = k === shape.length - 1 ? s.dur : Math.min(s.dur, t + Math.round(s.dur * share));
    if (end <= t) return;
    segValues.push(`ROW(${s.id}, ${k + 1}, ${t}, ${end}, ${r3(clamp(s.f.energy + de + between(-0.03, 0.03)))}, ${r3(clamp(s.f.valence + dv + between(-0.03, 0.03)))})`);
    t = end;
  });
});
