  const playable = (s) => !(u.u === 'nila' && s.explicit);
  let budget = u.plays;
  const dayPlan = [];
  for (let d = 59; d >= 0; d--) {
    const activeProb = d < 7 ? 0.85 : 0.62;
    if (d <= 5 || rand() < activeProb) dayPlan.push(d); // last 6 days always active -> live streak
  }
  const perDay = budget / dayPlan.length;
  for (const d of dayPlan) {
    let n = Math.max(2, Math.round(perDay + between(-2, 3)));
    const nSessions = n > 7 && rand() < 0.5 ? 2 : 1;
    const hours = [...u.hours].sort(() => rand() - 0.5).slice(0, nSessions).sort((a, b) => a - b);
    for (const hour of hours) {
      const size = Math.max(2, Math.round(n / nSessions));
      sessionId += 1;
      const ctx = rand() < 0.5 ? pick(u.contexts) : null;
      const startMinute = hour * 60 + int(0, 45);
      const daySql = d === 0 ? null : d;
      const sess = { id: sessionId, user: u.id, ctx, d, startMinute, plays: 0, secs: 0, offset: 0 };
      let last = null;
      for (let k = 0; k < size; k++) {
        let song;
        const r = rand();
        if (last && last.completed && u.arch.includes(last.song.arch) && rand() < 0.14) song = last.song;   // replay a loved song
        else if (d < 7 && r < 0.14) song = songByTitle[pick(RISING)];
        else if (d >= 7 && d < 14 && r < 0.12) song = songByTitle[pick(COOLING)];
        else if (r < 0.70) song = pick(favLang.length ? favLang : favAny);
        else if (r < 0.86) song = pick(favAny);
        else song = pick(others);
        if (!playable(song)) song = pick(favLang);
        const isFav = u.arch.includes(song.arch) || RISING.includes(song.title);
        const o = rand();
        let listened;
        if (isFav ? o < 0.8 : o < 0.35) listened = song.dur;
        else if (isFav ? o < 0.9 : o < 0.55) listened = Math.round(song.dur * between(0.45, 0.85));
        else listened = int(6, 25);
        playId += 1;
        const startOffset = sess.offset;
        plays.push({ id: playId, session: sess, song, startOffset, listened, origin: pick(['HOME', 'HOME', 'MOOD', 'CONTEXT', 'SEARCH', 'PLAYLIST', 'LIBRARY']) });
        events.push([playId, 'PLAY_STARTED', 0, null, startOffset]);
        if (listened > 60 && rand() < 0.12) {
          const at = int(20, Math.min(listened - 10, 50));
          events.push([playId, 'PAUSE', at, null, startOffset + at]);
          events.push([playId, 'RESUME', at, null, startOffset + at + int(5, 40)]);
        }
        if (listened > 60 && rand() < 0.06) {
          const at = int(10, 40);
          events.push([playId, 'SEEK', at, Math.min(song.dur - 1, at + int(20, 60)), startOffset + at + 1]);
        }
        const done = listened >= 0.9 * song.dur;
        events.push([playId, done ? 'COMPLETED' : 'SKIP', listened, null, startOffset + listened]);
        sess.offset += listened + int(1, 8);
        sess.plays += 1; sess.secs += listened;
        last = { song, completed: done };
      }
      sess.sqlStart = daySql === null
        ? `NOW() - INTERVAL ${Math.ceil(sess.offset / 60) + int(25, 200)} MINUTE`
        : `CURDATE() - INTERVAL ${daySql} DAY + INTERVAL ${startMinute} MINUTE`;
      sessions.push(sess);
      n -= size;
    }
  }
