// Writes docs/roadmap/DEPENDENCY_MAP.md and docs/roadmap/ROADMAP.md from feature-registry.json and the
// dependency graph produced by check-registry.js (run that first). Nothing here is hand-counted.
//   node backend/scripts/roadmap/build-roadmap-docs.js
// Developed by Vaishnav Sai.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../../..');
const REG = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/roadmap/feature-registry.json'), 'utf8'));
const G = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/roadmap/.build/dependency-graph.json'), 'utf8'));
const byId = Object.fromEntries(REG.features.map((f) => [f.id, f]));
const ORDER = ['VERIFIED', 'IMPLEMENTED-UNVERIFIED', 'PARTIAL', 'PLANNED', 'BLOCKED', 'NOT IMPLEMENTED'];
const statusLine = (fs_) => ORDER.map((s) => [s, fs_.filter((f) => f.status === s).length]).filter(([, n]) => n).map(([s, n]) => `${s} ${n}`).join(' · ');
const dependents = {};
for (const [id, ds] of Object.entries(G.deps)) for (const d of ds) (dependents[d] ||= []).push(Number(id));

// ------------------------------------------------------------------ dependency map
const edges = Object.entries(G.deps).flatMap(([id, ds]) => ds.map((d) => [d, Number(id)]));
const inGraph = [...new Set(edges.flat())].sort((a, b) => a - b);
const cls = { VERIFIED: 'v', 'IMPLEMENTED-UNVERIFIED': 'i', PARTIAL: 'p', PLANNED: 'pl', BLOCKED: 'b', 'NOT IMPLEMENTED': 'n' };
const dep = [
  '# Feature dependency map', '',
  '*Developed by Vaishnav Sai.* Generated by `backend/scripts/roadmap/build-roadmap-docs.js` from `feature-registry.json`.',
  'An arrow A → B means B needs A first: either B lists A in `dependsOn`, or B uses a table / column that A\'s migration creates.', '',
  `${edges.length} dependencies between ${inGraph.length} features; the other ${REG.features.length - inGraph.length} features stand alone on the existing schema.`, '',
  '## Graph', '', '```mermaid', 'flowchart LR',
  ...inGraph.map((id) => `  f${id}["#${id} ${byId[id].name.replace(/"/g, "'")}"]:::${cls[byId[id].status]}`),
  ...edges.map(([a, b]) => `  f${a} --> f${b}`),
  '  classDef v fill:#d9f2e3,stroke:#1d7a46', '  classDef i fill:#e6f0ff,stroke:#3567c8', '  classDef p fill:#fff4d6,stroke:#a77b00',
  '  classDef pl fill:#f1f1f1,stroke:#777', '  classDef b fill:#fde2e1,stroke:#b42318', '  classDef n fill:#ffffff,stroke:#999,stroke-dasharray: 4 3',
  '```', '', 'Colours: green VERIFIED · blue IMPLEMENTED-UNVERIFIED · amber PARTIAL · grey PLANNED · red BLOCKED · dashed NOT IMPLEMENTED.', '',
  '## Foundations (most other features build on these)', '',
  '| # | Feature | Status | Needed by |', '| --- | --- | --- | --- |',
  ...Object.entries(dependents).sort((a, b) => b[1].length - a[1].length || a[0] - b[0])
    .map(([id, list]) => `| ${id} | ${byId[id].name} | ${byId[id].status} | ${list.sort((a, b) => a - b).map((d) => `#${d}`).join(', ')} |`), '',
  '## Every feature', '',
  '| # | Feature | Dependency | Status | Needs first | Needed by |', '| --- | --- | --- | --- | --- | --- |',
  ...REG.features.map((f) => `| ${f.id} | ${f.name} | ${f.dependency} | ${f.status} | ${(G.deps[f.id] || []).map((d) => `#${d}`).join(', ') || '—'} | ${(dependents[f.id] || []).sort((a, b) => a - b).map((d) => `#${d}`).join(', ') || '—'} |`), '',
  '## External blockers', '', '| # | Feature | Type | What is needed |', '| --- | --- | --- | --- |',
  ...REG.features.filter((f) => f.outstanding).map((f) => `| ${f.id} | ${f.name} | ${f.dependency} | ${f.outstanding.join('; ')} |`), '',
];
fs.writeFileSync(path.join(ROOT, 'docs/roadmap/DEPENDENCY_MAP.md'), dep.join('\n'));

// ------------------------------------------------------------------ roadmap
const phaseFeatures = (p) => (p.features || REG.features.filter((f) => f.phase === p.id).map((f) => f.id)).map((id) => byId[id]);
const migFor = (fs_) => [...new Set(fs_.map((f) => f.newDb?.migration).filter(Boolean))];
const rm = [
  '# LOOP × MUSE — project roadmap (87 features)', '',
  '*Developed by Vaishnav Sai.* Generated from `feature-registry.json`; statuses come from code and passing tests only (see FEATURE_REGISTRY.md).', '',
  `**Today:** ${statusLine(REG.features)}.`, '',
  '**Database:** the application database and the academic submission both stay at the 64-table baseline (migrations 0000–0004).',
  'Proposed migrations `0005_roadmap_33_57.sql` (16 tables) and `0006_roadmap_58_87.sql` (14 tables) live in `database/migrations/proposed/`, which the migration runner does not read. They have been tested only on disposable schemas.', '',
  '## Phases', '',
];
for (const p of REG.phases) {
  const list = phaseFeatures(p);
  const migs = migFor(list);
  rm.push(`### ${p.name}`, '', list.length ? `${statusLine(list)}${migs.length ? ` · schema: ${migs.map((m) => `\`${path.basename(m)}\``).join(', ')}` : ' · no schema change'}` : '', '');
  if (list.length) {
    rm.push('| # | Feature | Dependency | Status | Needs first |', '| --- | --- | --- | --- | --- |',
      ...list.map((f) => `| ${f.id} | ${f.name} | ${f.dependency} | ${f.status} | ${(G.deps[f.id] || []).map((d) => `#${d}`).join(', ') || '—'} |`), '');
  }
}
rm.push('## Recommended order of work', '',
  '1. **Close the gaps of existing features first** — the PARTIAL features in S1–S3 and P4 need no new tables; finishing them raises VERIFIED without schema risk.',
  '2. **P10 account and privacy items that need no migration** — 80 Personal Data Export and the remaining UI of 76/83/84 reuse existing tables.',
  '3. **Promote 0005 in slices, not all at once** — e.g. the user_follows + profile columns slice for 37, then playlist collaboration for 34/38, each passing the gate below before the next.',
  '4. **P8 and P9** — mostly computed features; 0006 objects are promoted only with the feature that uses them (bookmarks with 63, revisions with 66, …).',
  '5. **P11 operations** — 83/84 first (read-only), then flags (86) before experiments (85); backups (82) need server infrastructure.',
  '6. **P7 provider/platform features stay BLOCKED** until the listed external requirement exists; no mock or placeholder integration is shipped.', '',
  '## Release gate (every phase)', '', ...REG.phaseGate.map((g, i) => `${i + 1}. ${g}`), '');
fs.writeFileSync(path.join(ROOT, 'docs/roadmap/ROADMAP.md'), rm.join('\n'));
console.log(`wrote DEPENDENCY_MAP.md (${edges.length} edges) and ROADMAP.md`);
