// Builds the MySQL Workbench versions of the MUSE database scripts from the real
// source files (database/01-07 + database/migrations), so they can never drift:
//
//   database/workbench/MUSE_Workbench_Setup.sql          whole database: schema, functions, views,
//                                                        procedures, triggers, demo data, migrations
//   database/workbench/MUSE_Workbench_AppUser_OPTIONAL.sql  least-privilege app account (edit the password first)
//   database/workbench/MUSE_Workbench_Queries.sql        the 40 analytical queries, transactions and EXPLAINs
//
//   node backend/scripts/build-workbench-sql.js
//
// It follows exactly the path of `npm run db:setup`: baseline (01-05) → baseline mark →
// seed (07) → migrations 0001-0003, each recorded in schema_migrations with the same
// SHA-256 checksum, so `npm run db:status` / `db:migrate` work on a database made this way.
// Grants for the application account are moved to the OPTIONAL file, because they need
// a user and password that only the person running the script should choose.
const fs = require('fs');
const path = require('path');
const migrations = require('./migrate');

const DB_DIR = path.resolve(__dirname, '../../database');
const OUT = path.join(DB_DIR, 'workbench');
const DB = 'muse';                 // matches DB_NAME in .env.example
const APP_USER = 'muse_app';       // matches DB_APP_USER in .env.example
const APP_HOST = 'localhost';
const BASELINE = ['01_schema.sql', '02_functions.sql', '03_views.sql', '04_procedures.sql', '05_triggers.sql'];

const read = (f) => fs.readFileSync(path.join(DB_DIR, f), 'utf8');
const isGrant = (line) => /^\s*(GRANT|REVOKE)\b.*__APP_USER__/i.test(line);
const subst = (s) => s.replace(/__DB__/g, DB).replace(/__APP_USER__/g, APP_USER).replace(/__APP_HOST__/g, APP_HOST);
const banner = (t) => `\n-- ${'='.repeat(69)}\n--  ${t}\n-- ${'='.repeat(69)}\n`;

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const grants = [];
  const setup = [];
  setup.push(`-- =====================================================================
--  MUSE — Music Mood Intelligence & Recommendation Database System
--  MUSE_Workbench_Setup.sql  —  creates the complete database in one run
--
--  GENERATED by backend/scripts/build-workbench-sql.js from database/01-07 and
--  database/migrations. Do not edit this file; edit the sources and regenerate.
--
--  HOW TO RUN (MySQL Workbench 8.0, MySQL Server 8.0.19 or newer):
--    1. Connect as root (or another account with CREATE / DROP / TRIGGER /
--       CREATE ROUTINE / CREATE VIEW / EVENT rights).
--    2. File > Run SQL Script... > choose this file > Run.
--       (Or open it in a query tab and press the lightning bolt ⚡ "Execute all".)
--    3. Refresh the Schemas panel: database "${DB}" appears with 63 tables, 19 views,
--       stored functions and procedures, and triggers.
--
--  WARNING: the first statements DROP the database "${DB}" if it exists, so running
--  this again resets it to the original demo data.
--
--  If you get error 1418 ("... binary logging is enabled ..."), run this once
--  as root and then run the script again:
--      SET GLOBAL log_bin_trust_function_creators = 1;
-- =====================================================================

DROP DATABASE IF EXISTS \`${DB}\`;
CREATE DATABASE \`${DB}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE \`${DB}\`;
-- same session settings as npm run db:setup (the Node driver's defaults and DB_TIMEZONE in .env.example)
SET NAMES utf8mb4 COLLATE utf8mb4_general_ci;
SET time_zone = '+00:00';
-- Workbench turns "Safe Updates" on by default; the demo data uses bulk UPDATEs, so switch
-- it off for this script only (restored at the end)
SET @muse_old_safe_updates = @@SESSION.SQL_SAFE_UPDATES;
SET SQL_SAFE_UPDATES = 0;
`);
  for (const f of BASELINE) {
    const text = read(f);
    if (text.split('\n').some(isGrant)) throw new Error(`${f} contains grants; expected only in 06/migrations`);
    setup.push(banner(`database/${f}`), subst(text).trimEnd(), '');
  }
  setup.push(banner('baseline recorded in schema_migrations (as backend/scripts/migrate.js does)'), `CREATE TABLE IF NOT EXISTS schema_migrations (
  version      CHAR(4)      NOT NULL,
  name         VARCHAR(120) NOT NULL,
  checksum     CHAR(64)     NULL,
  applied_at   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  execution_ms INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (version),
  CONSTRAINT chk_mig_version CHECK (version REGEXP '^[0-9]{4}$')
) ENGINE=InnoDB;
INSERT IGNORE INTO schema_migrations (version, name, checksum) VALUES ('${migrations.BASELINE.version}', '${migrations.BASELINE.name}', NULL);
`);
  setup.push(banner('database/07_seed.sql  (demo data)'), subst(read('07_seed.sql')).trimEnd(), '');
  setup.push(banner('migrations'), '-- 07_seed.sql switched the session collation; pin it again as migrate.js does',
    'SET NAMES utf8mb4 COLLATE utf8mb4_general_ci;', '');
  for (const m of migrations.files()) {
    const kept = [];
    for (const line of m.text.split('\n')) (isGrant(line) ? grants.push(`${subst(line)}   -- from migration ${m.file}`) : kept.push(line));
    setup.push(banner(`database/migrations/${m.file}`), subst(kept.join('\n')).trimEnd(), '',
      `INSERT INTO schema_migrations (version, name, checksum, execution_ms) VALUES ('${m.version}', '${m.name}', '${m.checksum}', 0);`, '');
  }
  setup.push(banner('done — quick check'), `SELECT 'tables' AS object, COUNT(*) AS how_many FROM information_schema.tables WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE'
UNION ALL SELECT 'views', COUNT(*) FROM information_schema.views WHERE table_schema = DATABASE()
UNION ALL SELECT 'functions + procedures', COUNT(*) FROM information_schema.routines WHERE routine_schema = DATABASE()
UNION ALL SELECT 'triggers', COUNT(*) FROM information_schema.triggers WHERE trigger_schema = DATABASE()
UNION ALL SELECT 'songs', COUNT(*) FROM songs
UNION ALL SELECT 'users', COUNT(*) FROM users
UNION ALL SELECT 'listening_history rows', COUNT(*) FROM listening_history;
SELECT version, name FROM schema_migrations ORDER BY version;
SET SQL_SAFE_UPDATES = @muse_old_safe_updates;
`);
  fs.writeFileSync(path.join(OUT, 'MUSE_Workbench_Setup.sql'), setup.join('\n'));

  // ---- optional least-privilege account
  const sec = subst(read('06_security.sql')).replace(/__APP_PASSWORD__/g, 'CHANGE_ME_BEFORE_RUNNING');
  if (!sec.includes("IDENTIFIED BY 'CHANGE_ME_BEFORE_RUNNING'")) throw new Error('06_security.sql: password placeholder not found');
  fs.writeFileSync(path.join(OUT, 'MUSE_Workbench_AppUser_OPTIONAL.sql'), `-- =====================================================================
--  MUSE — OPTIONAL: the least-privilege account the web application uses
--  GENERATED by backend/scripts/build-workbench-sql.js from database/06_security.sql
--  and the GRANT lines of the migrations.
--
--  Only needed if you will run the MUSE web app against this database.
--  BEFORE RUNNING: replace CHANGE_ME_BEFORE_RUNNING below with your own password
--  and put the same password in DB_APP_PASSWORD in your .env (never commit .env).
--  Run after MUSE_Workbench_Setup.sql, as root.
-- =====================================================================
USE \`${DB}\`;
${sec.trimEnd()}

-- grants added by later migrations
${grants.join('\n')}
FLUSH PRIVILEGES;
`);

  // ---- queries (unchanged apart from a header)
  fs.writeFileSync(path.join(OUT, 'MUSE_Workbench_Queries.sql'), `-- Copy of database/08_queries.sql (generated). Run after MUSE_Workbench_Setup.sql.
-- In Workbench: put the cursor in one query and press Ctrl+Enter to run just that query.
USE \`${DB}\`;
${read('08_queries.sql')}`);

  // ---- live demo: the database's own stored procedures produce a recommendation list and a
  // trend snapshot (the web app normally triggers these; here they run straight from SQL)
  fs.writeFileSync(path.join(OUT, 'MUSE_Workbench_Demo.sql'), `-- =====================================================================
--  MUSE — live demo in MySQL Workbench (run after MUSE_Workbench_Setup.sql)
--  GENERATED by backend/scripts/build-workbench-sql.js
--
--  In the web app these steps run when a listener asks for music / when the
--  weekly pipeline runs. Here the SAME stored procedures are called directly:
--    1. sp_generate_trend_snapshot   fills trend_snapshots (24 h / 7 d / 30 d)
--    2. sp_generate_recommendations  scores the catalogue for one listener and
--                                    writes recommendation_items + recommendation_reasons
--  Safe to run more than once (each run makes a new batch / a new job).
-- =====================================================================
USE \`${DB}\`;
SET @uid  = 3;          -- demo listener "aarav"
SET @mood = 'Calm';     -- try: Happy, Energetic, Romantic, Sad, Focused ...

-- 1. Trend snapshot -------------------------------------------------------
INSERT INTO pipeline_jobs (job_type, idempotency_key, params, processing_version, status, started_at)
VALUES ('TREND_SNAPSHOT', CONCAT('workbench-trend:', DATE_FORMAT(NOW(6), '%Y%m%d%H%i%s%f')), JSON_OBJECT('from', 'workbench'), '1.0', 'PROCESSING', NOW());
SET @job = LAST_INSERT_ID();
CALL sp_generate_trend_snapshot(@job);
UPDATE pipeline_jobs SET status = 'COMPLETED', completed_at = NOW() WHERE job_id = @job;
SELECT * FROM v_trending_songs LIMIT 10;

-- 2. A mood recommendation list for the listener -------------------------
START TRANSACTION;
INSERT INTO recommendation_batches
  (user_id, model_id, strategy, label, target_energy, target_valence, target_danceability, target_acousticness,
   target_instrumentalness, tempo_min, tempo_max, max_speechiness, discovery_only)
SELECT @uid, fn_active_model('RECOMMENDER'), 'MOOD', CONCAT(m.name, ' (Workbench demo)'), m.target_energy, m.target_valence,
       m.target_danceability, m.target_acousticness, m.target_instrumentalness, m.tempo_min, m.tempo_max, 1, 0
FROM moods m WHERE m.name = @mood;
SET @batch = LAST_INSERT_ID();
INSERT INTO recommendation_batch_moods (batch_id, mood_id, weight) SELECT @batch, mood_id, 1.00 FROM moods WHERE name = @mood;
CALL sp_generate_recommendations(@batch, 10);
COMMIT;

-- the list, best first, with the reasons stored for each song
SELECT ri.rank_position AS \`rank\`, s.title, a.name AS artist, ri.final_score,
       (SELECT GROUP_CONCAT(e.reason_text SEPARATOR ' | ') FROM v_recommendation_explanations e
         WHERE e.batch_id = ri.batch_id AND e.song_id = ri.song_id) AS why
FROM recommendation_items ri
JOIN songs s   ON s.song_id = ri.song_id
JOIN artists a ON a.artist_id = s.primary_artist_id
WHERE ri.batch_id = @batch
ORDER BY ri.rank_position;
`);

  for (const f of fs.readdirSync(OUT)) console.log(`  ${f.padEnd(40)} ${(fs.statSync(path.join(OUT, f)).size / 1024).toFixed(0)} KB`);
  console.log(`  ${grants.length} migration grant(s) moved to the OPTIONAL file`);
}

main();
