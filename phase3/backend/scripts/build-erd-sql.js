// Structure-only SQL for drawing the ER diagram in MySQL Workbench (no data, no views,
// routines or triggers: only tables, keys, constraints and foreign keys).
// Read from the live database, so it is always the real final schema.
//
//   node backend/scripts/build-erd-sql.js
//
//   database/workbench/MUSE_ERD_Structure_Full.sql    every data table, every foreign key  -> database muse_erd
//   database/workbench/MUSE_ERD_Structure_Core.sql    the core tables (docs/erd/MUSE_ERD_Core),
//                                                     foreign keys between them           -> database muse_erd_core
// They use their own database names so they never touch the "muse" database with the data.
const fs = require('fs');
const path = require('path');
const mysql = require('mysql2/promise');
const { db } = require('../src/config/env');

const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'database', 'workbench');
const CORE = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs', 'erd', 'core-mapping.json'), 'utf8')).coreEntities;

function order(names, refs) {
  // parents before children (self-references ignored), so the script also runs with FK checks on
  const done = new Set();
  const out = [];
  const visit = (t, stack = new Set()) => {
    if (done.has(t)) return;
    if (stack.has(t)) throw new Error(`foreign-key cycle at ${t}`);
    stack.add(t);
    for (const p of refs[t] || []) if (p !== t && names.includes(p)) visit(p, stack);
    done.add(t);
    out.push(t);
  };
  names.forEach((t) => visit(t));
  return out;
}

function header(title, dbName, lines) {
  return `-- =====================================================================
--  MUSE — ${title}
--  STRUCTURE ONLY: tables, columns, primary / unique / foreign keys, CHECK
--  constraints and indexes. No data rows, views, procedures or triggers.
--  GENERATED by backend/scripts/build-erd-sql.js from the live schema
--  (baseline + migrations 0001–0003). Do not edit; regenerate.
--
${lines.map((l) => `--  ${l}`).join('\n')}
--
--  To draw the ER diagram in MySQL Workbench (choose ONE):
--   A) File > Import > Reverse Engineer MySQL Create Script... > pick this file
--      > tick "Place imported objects on a diagram" > Execute. (No server needed.)
--   B) Run this file (File > Run SQL Script...), then Database > Reverse Engineer...
--      > your connection > schema "${dbName}" > Execute.
--  Then File > Export > Export as PNG / PDF.
--
--  It creates its own database "${dbName}"; your "muse" database is not touched.
-- =====================================================================

DROP DATABASE IF EXISTS \`${dbName}\`;
CREATE DATABASE \`${dbName}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE \`${dbName}\`;
`;
}

(async () => {
  const c = await mysql.createConnection({ host: db.host, port: db.port, user: db.ownerUser, password: db.ownerPassword, database: db.database });
  const [tables] = await c.query(`SELECT TABLE_NAME n FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE'
                                   AND TABLE_NAME <> 'schema_migrations' ORDER BY TABLE_NAME`, [db.database]);
  const names = tables.map((r) => r.n);
  const [fkRows] = await c.query(`SELECT DISTINCT TABLE_NAME t, REFERENCED_TABLE_NAME p FROM information_schema.KEY_COLUMN_USAGE
                                   WHERE TABLE_SCHEMA = ? AND REFERENCED_TABLE_NAME IS NOT NULL`, [db.database]);
  const refs = {};
  fkRows.forEach((r) => (refs[r.t] = refs[r.t] || []).push(r.p));
  const ddl = {};
  for (const t of names) {
    const [[row]] = await c.query(`SHOW CREATE TABLE \`${t}\``);
    ddl[t] = row['Create Table'].replace(/ AUTO_INCREMENT=\d+/, '');
  }
  await c.end();
  for (const t of CORE) if (!names.includes(t)) throw new Error(`core table ${t} not in the schema`);

  const countFks = (sql) => (sql.match(/FOREIGN KEY/g) || []).length;

  // ---- full: every table except schema_migrations (migration bookkeeping, not part of the data model)
  const full = order(names, refs);
  let fullFks = 0;
  const fullSql = [header('ER diagram structure: all tables', 'muse_erd', [
    `${full.length} data tables (schema_migrations, the migration bookkeeping table, is left out).`,
    `For the ${CORE.length}-entity version use MUSE_ERD_Structure_Core.sql.`])];
  for (const t of full) {
    fullFks += countFks(ddl[t]);
    fullSql.push(`${ddl[t]};\n`);
  }
  fs.writeFileSync(path.join(OUT, 'MUSE_ERD_Structure_Full.sql'), fullSql.join('\n'));

  // ---- core: same tables, but foreign keys to tables outside the core are left out
  //      (the column stays, so no content is lost; only the line to a table not drawn is dropped)
  const core = order(CORE, refs);
  let coreFks = 0;
  const dropped = [];
  const coreSql = [header(`ER diagram structure: ${CORE.length} core entities`, 'muse_erd_core', [
    `The ${CORE.length} core tables with ALL their columns and keys (see docs/erd/MUSE_ERD_Core_GUIDE.md).`,
    `Foreign keys that point to tables outside these ${CORE.length} are left out here, so they do not`,
    'draw lines to missing tables; the columns themselves are kept. The real database still',
    `has those foreign keys and ${names.length + 1} tables in total.`])];
  for (const t of core) {
    const lines = ddl[t].split('\n');
    const kept = [];
    for (const l of lines) {
      const m = l.match(/CONSTRAINT `([^`]+)` FOREIGN KEY \(([^)]+)\) REFERENCES `([^`]+)`/);
      if (m && !CORE.includes(m[3])) { dropped.push(`${t}(${m[2].replace(/`/g, '')}) -> ${m[3]}`); continue; }
      kept.push(l);
    }
    // the line before ") ENGINE" must not end with a comma after removing constraints
    const closing = kept.findIndex((l) => /^\) ENGINE/.test(l));
    kept[closing - 1] = kept[closing - 1].replace(/,$/, '');
    const sql = kept.join('\n');
    coreFks += countFks(sql);
    coreSql.push(`${sql};\n`);
  }
  coreSql.push(`-- Foreign keys left out of this ${CORE.length}-table version (present in the real database):\n${dropped.map((d) => `--   ${d}`).join('\n')}\n`);
  fs.writeFileSync(path.join(OUT, 'MUSE_ERD_Structure_Core.sql'), coreSql.join('\n'));

  console.log(`full: ${full.length} tables, ${fullFks} foreign keys`);
  console.log(`core: ${core.length} tables, ${coreFks} foreign keys, ${dropped.length} left out`);
})().catch((e) => { console.error(e.message); process.exitCode = 1; });
